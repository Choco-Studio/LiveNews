const BASE_COUNT = LIBRARY.count;
const copyTracks = (tr) => Object.fromEntries(Object.entries(tr).map(([k, v]) => [k, v.map((key) => key.map((x) => (Array.isArray(x) ? x.slice() : x)))]));

/** Finger pop times for the k-th counted finger (the approved rhythm for 1-3, then every 0.52 s). */
const POPS = [0.62, 1.06, 1.6, 2.12, 2.64];

/**
 * count with n fingers (1..5): index, middle, ring, pinky, then the thumb, each springing open
 * with a small overshoot on the approved rhythm; the wrist gives a little beat before each new
 * finger. n = 3 is exactly the approved gesture.
 */
function countForN(n) {
  if (n === 3) return { dur: BASE_COUNT.dur, stroke: BASE_COUNT.stroke, apex: BASE_COUNT.apex, hold: BASE_COUNT.hold, tracks: copyTracks(BASE_COUNT.tracks) };
  const last = POPS[n - 1];
  const dur = +(last + 1.2).toFixed(2);
  const wrist = [[0, 'R'], [0.18, [-7.4, 22.2, 11]], [0.48, [-1.0, 4.4, 13.0]], [0.58, [-0.6, 2.6, 13.2]], [0.72, [-0.8, 3.4, 13.1], 's']];
  for (let k = 1; k < n; k++) {
    wrist.push([POPS[k] - 0.14, [-0.75, 4.4, 13.1]]);
    wrist.push([POPS[k] - 0.06, [-0.65, 3.2, 13.1], 's']);
  }
  wrist.push([last + 0.42, [-0.6, 3.6, 13.1], 's'], [dur - 0.36, [-6.2, 21.4, 11.6]], [dur, 'R', 's']);
  // finger order: index, middle, ring, pinky, thumb (curl array is thumb..pinky)
  const ORDER = [1, 2, 3, 4, 0];
  const curl = [[0, 'R'], [0.42, FIST, 's'], [0.62, FIST, 's']];
  for (let k = 0; k < n; k++) {
    const after = COUNT[k + 1].slice();
    const over = after.slice();
    over[ORDER[k]] = k === 4 ? -0.1 : -0.08; // the finger springs a touch past straight
    const p = POPS[k];
    curl.push([p + 0.12, over], [p + 0.2, after, 's']);
    curl.push([k + 1 < n ? POPS[k + 1] : last + 0.5, after, 's']);
  }
  curl.push([dur - 0.3, 'R']);
  const pitch = [[0, 0]];
  const brow = [[0, 0]];
  for (let k = 0; k < n; k++) {
    const p = POPS[k];
    pitch.push([p + 0.08, 0.02], [p + 0.18, 0.05], [p + 0.33, 0]);
    brow.push([p + 0.13, 0.35 + 0.05 * k], [p + 0.33, 0.15]);
  }
  pitch.push([dur, 0]);
  brow.push([dur - 0.2, 0]);
  return {
    dur,
    stroke: 0.18,
    apex: 0.58,
    hold: last + 0.42,
    tracks: {
      wrist,
      dir: [[0, 'R'], [0.3, [-0.5, -0.3, 0.6]], [0.6, [-0.12, -1, 0.2]], [0.72, [-0.08, -1, 0.12], 's'], [last + 0.46, [-0.08, -1, 0.12], 's'], [dur - 0.3, [-0.7, 0.25, 0.55]], [dur, 'R']],
      curl,
      spread: [[0, 'R'], [0.6, 0.2], [last + 0.4, 0.2 + 0.08 * n], [dur - 0.3, 'R']],
      facing: [[0, 'R'], [0.42, 1, 's'], [dur - 0.6, 1, 's'], [dur - 0.3, 'R']],
      pole: [[0, 'R'], [0.5, [1, 1, 0]], [dur - 0.7, [1, 1, 0]], [dur, 'R']],
      shN: [[0, 0], [0.18, 0.3], [0.55, -0.4], [dur - 0.7, -0.35], [dur - 0.3, 0.1], [dur, 0]],
      pitch,
      brow,
      lookX: [[0, 0], [0.5, -0.15], [0.8, 0], [dur, 0]],
      lean: [[0, 0], [0.5, 0.01], [dur - 0.6, 0.01], [dur, 0]],
    },
  };
}
BASE_COUNT.forN = countForN;

